export function getRandomPuzzle(): CrosswordPuzzle {
  const validPuzzles = CROSSWORD_PUZZLES.filter(p => p.clues.length > 0);
  return validPuzzles[Math.floor(Math.random() * validPuzzles.length)];
}

export function getPuzzleById(id: number): CrosswordPuzzle | undefined {
  return CROSSWORD_PUZZLES.find(p => p.id === id);
}

